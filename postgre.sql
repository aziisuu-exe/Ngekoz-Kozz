-- ============================================================
--  FUNGSI GLOBAL (UPDATED_AT TRIGGER)
-- ============================================================
CREATE OR REPLACE FUNCTION set_current_timestamp_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

