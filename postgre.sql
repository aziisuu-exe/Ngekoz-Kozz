-- 1. Sync Latitude/Longitude ke PostGIS Location (Detail Kos)
CREATE OR REPLACE FUNCTION sync_kos_location()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.latitude IS NOT NULL AND NEW.longitude IS NOT NULL THEN
        NEW.location = ST_SetSRID(ST_MakePoint(NEW.longitude, NEW.latitude), 4326);
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_sync_kos_location
BEFORE INSERT OR UPDATE OF latitude, longitude ON detail_kos
FOR EACH ROW EXECUTE FUNCTION sync_kos_location();

-- 2. Auto Update Rating Kos saat ada Review
CREATE OR REPLACE FUNCTION update_kos_rating()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        UPDATE detail_kos
        SET rating_avg = COALESCE((SELECT ROUND(AVG(rating), 2) FROM review WHERE id_detail_kos = OLD.id_detail_kos), 0.00),
            total_reviews = (SELECT COUNT(*) FROM review WHERE id_detail_kos = OLD.id_detail_kos)
        WHERE id = OLD.id_detail_kos;
        RETURN OLD;
    ELSE
        UPDATE detail_kos
        SET rating_avg = COALESCE((SELECT ROUND(AVG(rating), 2) FROM review WHERE id_detail_kos = NEW.id_detail_kos), 0.00),
            total_reviews = (SELECT COUNT(*) FROM review WHERE id_detail_kos = NEW.id_detail_kos)
        WHERE id = NEW.id_detail_kos;
        RETURN NEW;
    END IF;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_review_after_insert_update
AFTER INSERT OR UPDATE ON review
FOR EACH ROW EXECUTE FUNCTION update_kos_rating();

CREATE TRIGGER trg_review_after_delete
AFTER DELETE ON review
FOR EACH ROW EXECUTE FUNCTION update_kos_rating();

-- 3. Auto Update last_message_at di Percakapan
CREATE OR REPLACE FUNCTION update_percakapan_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE percakapan
    SET last_message_at = NEW.created_at
    WHERE id = NEW.id_percakapan;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_pesan_after_insert
AFTER INSERT ON pesan
FOR EACH ROW EXECUTE FUNCTION update_percakapan_timestamp();

-- 4. Auto Update Ketersediaan Kamar dari Status Reservasi
CREATE OR REPLACE FUNCTION update_kamar_tersedia()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.status IS DISTINCT FROM NEW.status THEN
        -- Jika bayar, kurangi stok
        IF NEW.status = 'paid' AND OLD.status != 'paid' THEN
            UPDATE kamar_kos
            SET kamar_tersedia = GREATEST(0, kamar_tersedia - 1),
                is_available = CASE WHEN (kamar_tersedia - 1) > 0 THEN TRUE ELSE FALSE END
            WHERE id = NEW.id_kamar;
        END IF;
        -- Jika selesai/batal, kembalikan stok
        IF NEW.status IN ('completed', 'cancelled') AND OLD.status = 'paid' THEN
            UPDATE kamar_kos
            SET kamar_tersedia = kamar_tersedia + 1,
                is_available = TRUE
            WHERE id = NEW.id_kamar;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_reservasi_after_update
AFTER UPDATE ON reservasi
FOR EACH ROW EXECUTE FUNCTION update_kamar_tersedia();